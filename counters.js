function rank(enemies,role,heroes){const sc={},why={},weak={};heroes.filter(h=>h.role==role).forEach(h=>{sc[h.name]=0;why[h.name]=[];weak[h.name]=[]});
 for(const[a,b,r,src] of EDGES){if(!enemies.includes(b)&&!enemies.includes(a))continue;const w=src=='c'?3:2;
  if(a in sc&&enemies.includes(b)){sc[a]+=w;why[a].push({e:b,r})}
  if(b in sc&&enemies.includes(a)){sc[b]-=w*0.75;weak[b].push(a)}}
 return Object.entries(sc).filter(([,v])=>v>0).sort((x,y)=>y[1]-x[1]||x[0].localeCompare(y[0])).map(([n,v])=>({n,v,why:why[n],weak:weak[n]}))}
